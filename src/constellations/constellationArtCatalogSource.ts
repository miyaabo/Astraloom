import type { ConstellationArtRecord } from './constellationArtTypes'

/**
 * Validates a single record's shape at load time, mirroring
 * constellationCatalogSource.ts's isValidConstellationRecord (CLAUDE.md
 * Security Baseline: validate external/generated data at the point it's
 * consumed, not just wherever it happens to be generated).
 */
function isValidConstellationArtRecord(
  record: unknown,
): record is ConstellationArtRecord {
  if (typeof record !== 'object' || record === null) return false
  const {
    constellationNames,
    constellationId,
    imageUrl,
    imageWidthPx,
    imageHeightPx,
    pixelBounds,
    anchors,
    imagePath,
    guideImagePath,
    offsetX,
    offsetY,
    scale,
    rotationDeg,
    flipX,
    flipY,
    guideBounds,
  } = record as Record<string, unknown>

  if (!Array.isArray(constellationNames) || constellationNames.length === 0)
    return false
  if (
    !constellationNames.every(
      (name) => typeof name === 'string' && name.length > 0,
    )
  )
    return false
  if (typeof imageUrl !== 'string' || imageUrl.length === 0) return false
  if (typeof constellationId !== 'string' || constellationId.length === 0)
    return false
  if (typeof imageWidthPx !== 'number' || !Number.isFinite(imageWidthPx))
    return false
  if (typeof imageHeightPx !== 'number' || !Number.isFinite(imageHeightPx))
    return false
  if (!isValidPixelBounds(pixelBounds) || !isValidPixelBounds(guideBounds))
    return false
  if (typeof imagePath !== 'string' || imagePath.length === 0) return false
  if (typeof guideImagePath !== 'string' || guideImagePath.length === 0)
    return false
  if (
    typeof offsetX !== 'number' ||
    !Number.isFinite(offsetX) ||
    typeof offsetY !== 'number' ||
    !Number.isFinite(offsetY) ||
    typeof scale !== 'number' ||
    !Number.isFinite(scale) ||
    scale <= 0 ||
    typeof rotationDeg !== 'number' ||
    !Number.isFinite(rotationDeg)
  )
    return false
  if (typeof flipX !== 'boolean' || typeof flipY !== 'boolean') return false
  if (!Array.isArray(anchors)) return false

  const isValidAnchor = (anchor: unknown) => {
    if (typeof anchor !== 'object' || anchor === null) return false
    const { starId, pixelX, pixelY } = anchor as Record<string, unknown>
    return (
      typeof starId === 'number' &&
      Number.isFinite(starId) &&
      typeof pixelX === 'number' &&
      Number.isFinite(pixelX) &&
      typeof pixelY === 'number' &&
      Number.isFinite(pixelY)
    )
  }

  return anchors.every(isValidAnchor)
}

function isValidPixelBounds(bounds: unknown): boolean {
  if (typeof bounds !== 'object' || bounds === null) return false
  const { minX, minY, maxX, maxY } = bounds as Record<string, unknown>
  return (
    typeof minX === 'number' &&
    Number.isFinite(minX) &&
    typeof minY === 'number' &&
    Number.isFinite(minY) &&
    typeof maxX === 'number' &&
    Number.isFinite(maxX) &&
    typeof maxY === 'number' &&
    Number.isFinite(maxY)
  )
}

let cachedCatalog: ConstellationArtRecord[] | null = null

/**
 * Loads the pre-matched constellation art catalog (DECISIONS.md D033),
 * generated by scripts/build-constellation-art-catalog.mjs from hand-authored
 * anchor data (public/no-line/constellation-anchors.json) — see
 * constellationArtTypes.ts for the record shape and
 * docs/features/phase-13-implementation-tasks.md Task 4 for background on the
 * two earlier drawing approaches this one replaced.
 *
 * Dynamically imported (not a static top-level import) rather than assuming
 * the eventual real catalog stays small — once populated it's only ever
 * needed after a user actually selects a constellation, so bundling it
 * eagerly would grow the initial JS payload for no benefit on first paint
 * (Performance Rules / PRODUCT.md Mobile). Vite code-splits this into its own
 * chunk, fetched once and cached by the browser (and by `cachedCatalog` here)
 * on first use.
 */
export async function loadConstellationArtCatalog(): Promise<
  ConstellationArtRecord[]
> {
  if (cachedCatalog === null) {
    const module = await import('./data/constellationArt.json')
    cachedCatalog = (module.default as unknown[]).filter(
      isValidConstellationArtRecord,
    )
  }
  return cachedCatalog
}

let cachedRecordsByConstellationNamePromise: Promise<
  Map<string, ConstellationArtRecord>
> | null = null

/**
 * Builds (once) and caches the constellationName -> record lookup map.
 * Caches the in-flight promise itself, not just a "started" flag — Starfield.tsx
 * calls findConstellationArtByConstellationName and
 * computeConstellationArtPlacement concurrently via Promise.all, and both
 * resolve through this lookup, so two calls can arrive before either has
 * populated anything. Caching a bare `Map | null` guard let the second
 * caller see a non-null (but still empty) map and return null immediately,
 * instead of waiting for the first caller's population loop to finish.
 */
function getRecordsByConstellationName(): Promise<
  Map<string, ConstellationArtRecord>
> {
  if (cachedRecordsByConstellationNamePromise === null) {
    cachedRecordsByConstellationNamePromise =
      loadConstellationArtCatalog().then((records) => {
        const map = new Map<string, ConstellationArtRecord>()
        for (const record of records) {
          for (const name of record.constellationNames) {
            map.set(name, record)
          }
        }
        return map
      })
  }
  return cachedRecordsByConstellationNamePromise
}

/**
 * Finds the art record covering a given ConstellationRecord.name (not
 * `.id` — see constellationArtTypes.ts's ConstellationArtRecord doc comment
 * for why `.id` can't be used here), or null if that constellation has no
 * art record. A few images may cover several constellationNames (e.g. the
 * old Argo Navis figure covering Carina/Puppis/Vela/Pyxis, DECISIONS.md
 * D033); any of them should resolve to the same record.
 */
export async function findConstellationArtByConstellationName(
  constellationName: string,
): Promise<ConstellationArtRecord | null> {
  const recordsByName = await getRecordsByConstellationName()
  return recordsByName.get(constellationName) ?? null
}
