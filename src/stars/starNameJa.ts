/**
 * Display label for a star's proper name (Task 4): "English (Japanese)" when
 * a curated katakana name exists above, otherwise just the English proper
 * name on its own — matching how constellation labels pair `name`/`nameJa`
 * (see Starfield.tsx), but falling back gracefully since most of HYG's ~440
 * named stars have no curated entry here.
 */
export function toDisplayStarName(properName: string): string {
  const ja = STAR_NAME_JA[properName]
  return ja ? `${properName} (${ja})` : properName
}
